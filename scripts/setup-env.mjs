#!/usr/bin/env node
/**
 * Generates local development configuration from `.env.example`.
 *
 *   node scripts/setup-env.mjs          # create .env / apps/web/.env.local when missing
 *   node scripts/setup-env.mjs --force  # regenerate, including fresh secrets
 *
 * Secrets are generated with `crypto.randomBytes(32)` — never hardcoded, never
 * committed. The template (`.env.example`) is the single documented inventory of
 * every variable the system understands.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const force = process.argv.includes('--force');

const secret = () => randomBytes(32).toString('base64url');

const templatePath = path.join(root, '.env.example');
const template = readFileSync(templatePath, 'utf8');

/** Fills the empty variables in the template with usable development values. */
function renderDevelopmentEnv(source) {
  const generated = {
    IDENTIFIER_ENCRYPTION_KEY: secret(),
    IDENTIFIER_HASH_SECRET: secret(),
    ADMIN_PASSWORD: '"Simamia#Salama2026"',
  };

  return source
    .split('\n')
    .map((line) => {
      const match = /^([A-Z0-9_]+)=(.*)$/.exec(line);
      if (!match) return line;
      const [, key, value] = match;
      const replacement = generated[key];
      if (replacement !== undefined && value.trim() === '') return `${key}=${replacement}`;
      return line;
    })
    .join('\n');
}

const targets = [
  { path: path.join(root, '.env'), contents: renderDevelopmentEnv(template) },
  {
    path: path.join(root, 'apps/web/.env.local'),
    contents: [
      '# Generated by scripts/setup-env.mjs — not committed.',
      '# The Next.js server proxies /api/v1/* and /media/* to the Express API.',
      'API_BASE_URL=http://127.0.0.1:4000',
      '',
    ].join('\n'),
  },
];

let wrote = 0;
for (const target of targets) {
  if (!force && existsSync(target.path)) {
    console.log(`[setup-env] kept existing ${path.relative(root, target.path)}`);
    continue;
  }
  writeFileSync(target.path, target.contents, { mode: 0o600 });
  console.log(`[setup-env] wrote ${path.relative(root, target.path)}`);
  wrote += 1;
}

if (wrote > 0) {
  console.log('[setup-env] Local secrets are in .env (gitignored). Never reuse them in production.');
}
